# Revision of the machine card generator (`fetch_from_hf`). Bump whenever the
# GENERATED output changes in a way that makes previously generated cards
# worse than regenerating (backend tags, preference order, structural probing).
# Generated cards persist this value; at load time a generated card stamped
# with an older revision loses its override power against a bundled card for
# the same id (the bundled card is current truth), while a card with NO stamp
# is treated as hand-authored and keeps full #652 override precedence. Without
# this, a card generated by last month's Skulk silently pins a model to
# whatever that generator got wrong (the fresh-fleet audit found exactly that:
# pre-#652-fix cards forcing serial in-process llama_cpp over the served
# engine).
