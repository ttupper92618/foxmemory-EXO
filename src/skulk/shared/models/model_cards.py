class PlacementCardConfig(CamelCaseModel):
    """Hardware/routing constraints the planner reads from a model card (#149).

    The only card section the planner consults directly. Defaults describe the
    current implicit assumption (an MLX model with no extra memory floor), so
    cards without a ``[placement]`` section behave exactly as before.
    """

    compatible_backends: frozenset[str] = frozenset({"mlx"})
    """Hard constraint: only route to nodes whose advertised backends intersect
    this set. Making the implicit ``{"mlx"}`` explicit is what enables future
    heterogeneous (llama_cpp / rocm / cuda) routing."""

    min_vram_gib: float | None = None
    """Hard constraint: planner gates on node available memory when set."""

    max_context_tokens: int | None = None
    """Soft: caps the placement-time KV budget check (see #145) when set."""

    max_pipeline_split_layer: int | None = Field(default=None, ge=1)
    """Largest layer boundary at which a pipeline rank may begin.

    Some architectures end with layers that reuse KV produced by earlier
    concrete layers. Keeping every split at or before this boundary ensures the
    final rank owns those producers as well as their dependent tail. ``None``
    allows the planner to split at any ordinary layer boundary.
    """

    backend_preference: tuple[str, ...] = ()
    """Soft, ordered preference among the node's backend tags (e.g.
    ``("llama_cpp-vulkan", "llama_cpp-rocm")``).

    Unlike ``compatible_backends`` (a hard filter on which nodes are eligible),
    this only *ranks* eligible nodes/devices: the planner prefers a node that
    advertises an earlier-listed tag, and the runner picks the earliest-listed
    backend the chosen node actually has. The same model runs on any compatible
    backend, but their performance differs per model, so this captures "fastest
    on Vulkan, ROCm is an acceptable fallback" while still degrading gracefully
    to a node that only offers the fallback. Order is significant and preserved;
    an empty tuple means no preference (use the node's default)."""

    @field_validator("compatible_backends", mode="before")
    @classmethod
    def _coerce_compatible_backends(cls, v: object) -> object:
        # TOML provides a list (compatible_backends = ["mlx"]); strict mode
        # would reject it for a frozenset field and make any card with an
        # explicit [placement] section unloadable. Coerce before validation.
        if isinstance(v, (list, tuple, set, frozenset)):
            return frozenset(cast("Iterable[str]", v))
        return v

    @field_serializer("compatible_backends")
    def _serialize_compatible_backends(self, value: frozenset[str]) -> list[str]:
        # tomlkit cannot encode a frozenset, and ModelCard.save() now always
        # includes this section. Emit a sorted list for TOML and JSON alike.
        return sorted(value)

    @field_validator("backend_preference", mode="before")
    @classmethod
    def _coerce_backend_preference(cls, v: object) -> object:
        # TOML/JSON deliver a list; strict mode rejects a list for a tuple
        # field. Coerce while PRESERVING ORDER (unlike compatible_backends, the
        # preference is ranked, so it must not be turned into a set).
        if isinstance(v, (list, tuple)):
            return tuple(cast("Iterable[str]", v))
        return v

    @field_serializer("backend_preference")
    def _serialize_backend_preference(self, value: tuple[str, ...]) -> list[str]:
        # tomlkit cannot encode a tuple; emit an order-preserving list.
        return list(value)


class RuntimeCapabilityCardConfig(CamelCaseModel):
    """Optional runtime behavior hints for a model card."""

    prompt_renderer: PromptRendererType | None = None
    """How prompts are rendered for this model (``tokenizer`` chat template,
    ``gemma4``, ``dsml``); ``None`` uses the family default."""
    output_parser: OutputParserType | None = None
    """How model output is parsed (``generic``, ``gemma4``, ``gpt_oss``,
    ``deepseek_v32``), e.g. for reasoning/tool-call extraction; ``None`` uses the
    family default."""
    metal_fast_synch: bool | None = None
    """Per-model override for the MLX ``MLX_METAL_FAST_SYNCH`` flag.

    ``None`` means "no opinion" — fall through to the cluster default
    selected by the runner. Set explicitly to ``False`` for models that
    deadlock under FAST_SYNCH on the ring backend (e.g. gemma-4 with
    multimodal load: the Metal command queue wedges in
    ``pipeline_last_eval_output``, transitively starves WindowServer,
    and trips the macOS kernel watchdog into a panic). Set explicitly
    to ``True`` for models that have been measured to benefit and are
    known to be safe under the deployment's collective backend.
    """
    mtp_heads: bool | None = None
    """True when native MTP prediction heads are available via sidecar.

    Set alongside ``mtp_sidecar_repo``. When false or absent, the runner
    skips sidecar loading and uses standard autoregressive generation.
    """
    mtp_max_depth: int | None = None
    """Maximum draft depth the MTP heads support.

    Start at 1 for Apple Silicon. Deeper values can be evaluated via
    profiling but are unlikely to amortize on Metal due to near-linear
    verify-pass scaling.
    """
    mtp_sidecar_repo: str | None = None
    """Hugging Face repo ID containing the published ``mtp.safetensors`` sidecar.

    Example: ``"FoxlightAI/qwen3-5-7b-instruct-mtp-q4k"``
    The sidecar is downloaded alongside the base model weights and loaded
    into the runner for speculative decoding. Produced by SWP.
    """
    mtp_sidecar_revision: Annotated[str, Field(pattern=r"^[0-9a-f]{40}$")] | None = None
    """Immutable commit for a separate ``mtp_sidecar_repo``."""
    mtp_norm_convention: Literal["zero_centered", "actual_scale"] | None = None
    """How the sidecar stores its RMSNorm weights.

    ``"zero_centered"`` means deviation-from-1 (the raw Qwen3.5 checkpoint
    convention — the runner applies a +1.0 shift at load, mirroring what
    mlx-lm's ``sanitize()`` does for trunk weights). ``"actual_scale"`` means
    the stored value is the scale itself (DeepSeek convention). ``None``
    falls through to the family default keyed off the detected sidecar
    layout. Override per card when a publisher changes conventions — getting
    this wrong measured 0% draft acceptance on Qwen3.5-2B (issue #192).
    """
    mtp_concat_order: Literal["embed_first", "hidden_first"] | None = None
    """Concatenation order of the MTP fc projection input.

    ``"embed_first"`` = ``fc(concat([enorm(embed(t_next)), hnorm(h)]))`` —
    verified for Qwen3.5 (72.4% offline agreement, issue #192).
    ``"hidden_first"`` is the inherited DeepSeek assumption (unverified).
    ``None`` falls through to the family default keyed off the detected
    sidecar layout.
    """
    speculative_multi_node: bool | None = None
    """Whether speculation may run on multi-node placements of this model.

    ``None`` (default) places no restriction. Set ``False`` for models
    where multi-node speculation is measured SLOWER than plain distributed
    decode: the 2026-06-06 benchmark matrix found gemma-4-26B-A4B (MoE)
    at 30.2 tok/s plain vs 28.2 with MTP on a 2-node pipeline (-7%), while
    single-node MTP on the same model measures 2.2x — fast sharded MoE
    decode plus modest acceptance makes the per-round draft+verify
    overhead net negative. Single-node speculation is unaffected by this
    knob. The decision is card-driven so every rank makes the same
    speculate-or-not choice (the distributed agreement collective requires
    rank symmetry).
    """

    assistant_model_repo: str | None = None
    """Hugging Face repo ID of a companion *assistant* (drafter) model.

    Gemma 4 does speculative decoding differently from the Qwen3/DeepSeek
    ``mtp.*`` heads: instead of embedded prediction heads, it pairs the target
    with a separate small ``gemma4_assistant`` model (e.g.
    ``"mlx-community/gemma-4-26B-A4B-it-assistant-bf16"``) that cross-attends
    over the target's KV cache. When set, the assistant repo is downloaded
    alongside the base model. Mutually exclusive with the ``mtp_*`` fields.

    NOTE: consuming the assistant for speculative generation requires the
    ``gemma4_assistant`` drafter from mlx-vlm >= 0.5.0 and is not yet wired into
    the runner — declaring it here only pre-downloads it. See the Gemma 4 MTP
    initiative in the foxlight-docs hub (Phase C).
    """
    assistant_model_revision: (
        Annotated[str, Field(pattern=r"^[0-9a-f]{40}$")] | None
    ) = None
    """Immutable commit for a separate ``assistant_model_repo``."""
    served_spec_type: (
        Literal[
            "none",
            "draft_mtp",
            "draft_eagle3",
            "draft_simple",
            "draft_dflash",
            "ngram",
        ]
        | None
    ) = None
    """Speculative-decoding mode for the ``llama_server`` (served-backend) engine.

    Maps to a ``llama-server --spec-type`` token in the runner
    (``_SPEC_TYPE_FLAG``): ``draft_mtp`` -> ``draft-mtp`` (usually the model's own built-in
    MTP heads; a separate draft is optional, e.g. Gemma 4's assistant;
    Qwen3.6/DeepSeek/GLM/Kimi/Nemotron bake theirs in),
    ``draft_eagle3`` -> ``draft-eagle3`` (an EAGLE-3 head), ``draft_simple`` ->
    ``draft-simple`` (a separate draft model), ``draft_dflash`` ->
    ``draft-dflash`` (a separate block-parallel DFlash speculator GGUF via
    ``served_spec_draft_repo``/``served_spec_draft_file``; llama-server >=
    b10092), ``ngram`` -> ``ngram-cache`` (prompt-lookup), ``none``/``None``
    plain decoding. Only the served engine reads
    this; the in-process ``mlx`` and ``llama_cpp`` engines ignore it (MLX
    speculation is the ``mtp_*`` / ``assistant_model_repo`` fields above)."""
    served_spec_n_max: int | None = Field(default=None, gt=0)
    """Max draft tokens per step for the served engine (``--spec-draft-n-max``).

    Must be a positive integer (validated at card load so a bad value fails fast
    rather than producing an undefined ``--spec-draft-n-max`` at the server).
    ``None`` uses the llama-server default (3). Acceptance falls off with depth
    (per-position acceptance drops), so 2-3 is the usual sweet spot; tune per
    card from measured acceptance."""
    served_spec_draft_repo: str | None = None
    """Hugging Face repo of a separate **draft** GGUF for the served engine.

    Some served speculative modes need a second model passed to llama-server via
    ``--model-draft``, NOT built-in heads: ``draft_simple`` (a vocab-matched small
    draft model) and ``draft_eagle3`` (an EAGLE-3 head) always require one, and
    Gemma 4 ``draft_mtp`` uses its *assistant* as a separate draft GGUF (llama.cpp
    PR #23398) rather than baking heads into the base. Qwen3.6/DeepSeek/GLM
    ``draft_mtp`` leave this unset (heads are in the base GGUF). When set, the
    draft GGUF is downloaded as a companion alongside the base and passed as
    ``--model-draft``. Pairs with ``served_spec_draft_file``."""
    served_spec_draft_revision: (
        Annotated[str, Field(pattern=r"^[0-9a-f]{40}$")] | None
    ) = None
    """Immutable commit for a separate ``served_spec_draft_repo``."""
    served_spec_draft_file: str | None = None
    """Repo-relative GGUF filename of the served draft model (in
    ``served_spec_draft_repo``), e.g. ``"mtp-gemma-4-31B-it.gguf"``. Required when
    ``served_spec_draft_repo`` is set; selects the exact draft quant the runner
    passes to ``--model-draft``."""
    vllm_spec_method: Literal["mtp", "dflash"] | None = None
    """Speculative-decoding method for the ``vllm`` served engine.

    Maps to vLLM's ``--speculative-config`` ``method`` key. ``"mtp"`` engages
    the checkpoint's own native multi-token-prediction heads (vLLM resolves
    the matching drafter architecture, e.g. ``Qwen3_5MTP``, with no separate
    draft model); requires a checkpoint that ships MTP heads
    (``mtp_num_hidden_layers`` in its config). ``"dflash"`` engages a
    separate block-parallel DFlash speculator (Poolside's scheme, vLLM
    >= 0.25.0) and requires ``vllm_spec_draft_repo`` naming the drafter.
    Only the vllm engine reads this; ``served_spec_type`` remains the
    llama_server equivalent. The vocabulary starts deliberately narrow and
    grows as methods are validated live."""
    vllm_spec_num_tokens: int | None = Field(default=None, gt=0)
    """Draft tokens per step for vLLM speculative decoding
    (``--speculative-config`` ``num_speculative_tokens``).

    Requires ``vllm_spec_method``. Positive; acceptance falls per position
    (measured on Qwen3.6-27B-FP8: 86% at position 0, 69% at position 1), so
    2 is the usual sweet spot for single-layer MTP heads, which re-run their
    one layer for deeper positions. Block-parallel drafters (``dflash``)
    predict a whole block at once, so vendor-recommended depths run much
    deeper (Poolside ships 15 for a block size of 16). ``None`` uses vLLM's
    method default."""
    vllm_spec_draft_repo: str | None = None
    """Hugging Face repo of a separate draft/speculator model for vLLM
    speculative decoding (``--speculative-config`` ``model``).

    Required by draft-model methods (``dflash``); must be unset for
    ``mtp``, whose drafter lives inside the target checkpoint. The vllm
    engine passes the repo id through to ``vllm serve``, which resolves it
    from its own Hugging Face cache at engine start (the target model still
    stages through the Skulk model store; staging the draft through the
    store as a pinned companion is a follow-up)."""
    vllm_spec_draft_revision: (
        Annotated[str, Field(pattern=r"^[0-9a-f]{40}$")] | None
    ) = None
    """Immutable commit supplied to vLLM for ``vllm_spec_draft_repo``."""

    vllm_tool_call_parser: str | None = None
    """vLLM server-side tool-call parser name for this model
    (``--tool-call-parser``, paired with ``--enable-auto-tool-choice``).

    Engine-specific platform knob, so it lives in runtime beside the
    ``vllm_spec_*`` fields rather than in ``tooling`` (which stays model
    truth). This explicit field is the ONLY source: one family string can
    span tool-call generations with different wire formats, so there is no
    family fallback, and an unset field launches the server without tool
    support (tool requests are rejected loudly). Names follow vLLM's
    parser registry (hermes, llama3_json, mistral, pythonic, deepseek_v3,
    openai, ...); pin only pod-validated names."""
    vllm_reasoning_parser: str | None = None
    """vLLM server-side reasoning parser name for this model
    (``--reasoning-parser``).

    Same doctrine as ``vllm_tool_call_parser``: an engine-specific platform
    knob, explicit only, no family fallback. Without it vLLM streams a
    reasoning model's thinking inline with its answer (the server only splits
    ``reasoning_content`` when a parser is configured), so a card whose model
    always reasons (Muse Glimmer's ``to=self`` channel) must pin the parser
    that vLLM registers for the family (``muse_glimmer``, ``qwen3``,
    ``deepseek_r1``, ``openai_gptoss``, ...). Pin only pod-validated names."""

    @model_validator(mode="after")
    def _validate_vllm_spec_pairing(self) -> "RuntimeCapabilityCardConfig":
        """Reject inconsistent vllm speculative fields so custom cards fail
        fast at load, not silently at serve time.

        ``vllm_spec_num_tokens`` is meaningless without ``vllm_spec_method``
        (the runner would ignore it); ``dflash`` without a draft repo would
        fail at the server with an opaque vLLM error; a draft repo under
        ``mtp`` contradicts the method's in-checkpoint drafter contract.
        Bundled cards are gated by the invariant suite, but operator-authored
        custom cards deserve the same loud failure at load (PR #649 review).
        """
        if self.vllm_spec_num_tokens is not None and self.vllm_spec_method is None:
            raise ValueError("vllm_spec_num_tokens requires vllm_spec_method")
        if self.vllm_spec_method == "dflash" and self.vllm_spec_draft_repo is None:
            raise ValueError("vllm_spec_method 'dflash' requires vllm_spec_draft_repo")
        if self.vllm_spec_draft_repo is not None and self.vllm_spec_method != "dflash":
            raise ValueError("vllm_spec_draft_repo requires vllm_spec_method 'dflash'")
        return self

    @field_validator("prompt_renderer", mode="before")
    @classmethod
    def _validate_prompt_renderer(
        cls, value: str | PromptRendererType | None
    ) -> PromptRendererType | None:
        if value is None or isinstance(value, PromptRendererType):
            return value
        return PromptRendererType(value)

    @field_validator("output_parser", mode="before")
    @classmethod
    def _validate_output_parser(
        cls, value: str | OutputParserType | None
    ) -> OutputParserType | None:
        if value is None or isinstance(value, OutputParserType):
            return value
        return OutputParserType(value)


async def _resolve_hf_source_revision(
    model_id: ModelId,
    source_revision: str | None,
) -> str:
    """Resolve a model request to one immutable Hugging Face commit.

    Explicit model addition is the authorization decision for repository
    content, so it must never silently continue following a mutable branch.
    Existing full commit inputs are already validated by the API/card schema;
    omitted revisions resolve ``main`` exactly once before any artifact probe.

    Args:
        model_id: Hugging Face repository identifier.
        source_revision: Optional caller-supplied immutable commit.

    Returns:
        A lowercase 40-character Hub commit.

    Raises:
        ValueError: If the Hub does not return an immutable commit identity.
    """
    if source_revision is not None:
        return source_revision
    info = await to_thread.run_sync(lambda: model_info(model_id, revision="main"))
    resolved_revision = getattr(info, "sha", None)
    if not isinstance(resolved_revision, str) or re.fullmatch(
        r"[0-9a-fA-F]{40}", resolved_revision
    ) is None:
        raise ValueError(
            f"Hugging Face did not return an immutable revision for {model_id}"
        )
    return resolved_revision.lower()


class ModelCard(CamelCaseModel):
    """The persisted, declarative metadata Skulk holds for one model.

    This is the **model-card interface**: the single source of truth for how a
    model is sized, sharded, placed, and run. It is created once (from a
    HuggingFace repo or hand-authored), broadcast cluster-wide, and read by the
    planner (placement), the downloader (sizing + which files to fetch), and the
    worker runner (engine + behavior). As a ``CamelCaseModel`` it is camelCase on
    the wire and strict (``extra="forbid"``), so every node in a cluster must run
    the same Skulk version (a stale node rejects newer fields).

    Two layers live here: the *card* (this declarative metadata) and the
    normalized *resolved capability profile* derived from it plus family defaults
    (see ``capabilities.py`` and ``website/docs/model-capabilities.md``). The
    optional ``reasoning`` / ``modalities`` / ``tooling`` / ``runtime`` /
    ``vision`` / ``placement`` sub-configs refine that resolution; when absent,
    conservative family defaults apply.
    """

    model_id: ModelId
    """The selectable artifact alias. Historically this was always the upstream
    Hugging Face repository id; registry cards may use a distinct alias so two
    exact files or quants from one repository remain separate artifacts."""
    source_repository: ModelId | None = None
    """Upstream Hugging Face repository that owns the artifact bytes. ``None``
    means it is identical to ``model_id`` for legacy and locally generated cards."""
    storage_size: Memory
    """On-disk size of the weights this card loads (for a GGUF card, just the
    selected quant's shard group, not every quant the repo hosts). The planner
    uses this for memory-fit and placement-width decisions."""
    n_layers: PositiveInt
    """Number of transformer layers. Drives pipeline sharding (how layers split
    across nodes) and KV-cache sizing."""
    hidden_size: PositiveInt
    """Model hidden dimension, used in memory/KV-cache estimates."""
    supports_tensor: bool
    """Whether the model may be served with tensor parallelism (``Sharding.Tensor``).
    GGUF/llama.cpp cards set this ``False`` (single-node engine)."""
    num_key_value_heads: PositiveInt | None = None
    """KV-head count for grouped-query attention, used in KV-cache sizing. ``None``
    when unknown/not applicable."""
    tasks: list[ModelTask]
    """The task types this model serves (``TextGeneration``, ``TextEmbedding``,
    ``TextToImage``, ``ImageToImage``, ``TextToSpeech``, ``SpeechToText``,
    ``SpeechTranslation``); selects which runner handles it."""
    components: list[ComponentInfo] | None = None
    """For multi-component models (e.g. a diffusion stack), the per-component
    weight layout. ``None`` for a single-weights model."""
    family: str = ""
    """Model family token (e.g. ``qwen3``, ``gemma4``) used to pick family-specific
    defaults during capability resolution. Empty when not classified."""
    quantization: str = ""
    """Human quantization label (e.g. ``4bit``, ``Q4_K_M``); informational."""
    base_model: str = ""
    """The upstream base model id when this is a quant/finetune of another; empty
    if not applicable."""
    gguf_file: str | None = None
    """For GGUF (llama.cpp) models: the repo-relative path of the weights file the
    runner loads (the selected quant's first shard). Resolved once at card creation
    (preferring a quant over BF16) so the download fetches only that quant and the
    runner loads deterministically, instead of each layer re-globbing/guessing.
    ``None`` for non-GGUF (safetensors/MLX) cards."""
    artifact_bundle: ArtifactBundleConfig | None = None
    """Exact signed file selection and engine working directory for a v2 card.

    Legacy cards omit this field and preserve repository-wide tensor downloads.
    """
    source_revision: (
        Annotated[
            str,
            Field(pattern=r"^[0-9a-f]{40}$"),
        ]
        | None
    ) = None
    """Immutable Hugging Face commit for this card's model artifacts.

    ``None`` preserves the historical behavior of resolving the repository's
    mutable ``main`` branch. Curated or operator-authored cards should set this
    to a full commit hash when the exact artifact has been qualified, so an
    upstream file replacement cannot silently change what the store and workers
    execute.
    """
    capabilities: list[str] = []
    """Free-form capability tags carried for compatibility/auxiliary use; the
    structured ``reasoning``/``modalities``/``tooling`` configs are authoritative
    for capability resolution."""
    context_length: int = 0
    """The model's advertised maximum context length in tokens (``0`` if unknown).
    The admission ceiling is the smaller of this and what fits in memory."""
    uses_cfg: bool = False
    """Whether the model uses classifier-free guidance (relevant to some image /
    diffusion models)."""
    trust_remote_code: bool = True
    """Passed to the model loader: whether to execute the repo's custom Python.
    Defaults ``True`` to match upstream loaders; set ``False`` to refuse it."""
    is_custom: bool = False
    """Marks an operator-added custom card (not from the curated catalog). Excluded
    from the persisted card file so it is recomputed per environment."""
    qualification_only: bool = False
    """Marks an unsigned custom card owned by the temporary qualification lifecycle.

    The registry service credential may clean up only cards carrying this marker;
    ordinary operator-owned custom cards remain outside its deletion authority.
    """
    generator_revision: int | None = None
    """Revision of the machine card generator that produced this card
    (:data:`CARD_GENERATOR_REVISION` at generation time), persisted in the card
    file. ``None`` means hand-authored (or generated before revisions existed):
    such a card keeps full override precedence over a bundled card for the same
    id. A stamped card older than the current generator is superseded by the
    bundled card at load time, since a generated card is a cache of Hugging
    Face metadata plus generator logic, not operator intent."""
    vision: VisionCardConfig | None = None
    """Optional vision (image-input) configuration; ``None`` for text-only models."""
    reasoning: ReasoningCardConfig | None = None
    """Optional reasoning/thinking configuration (toggle, budget, format, default
    effort); ``None`` falls back to family defaults."""
    modalities: ModalitiesCardConfig | None = None
    """Optional extra-modality flags (audio input, native multimodal); ``None``
    falls back to family defaults."""
    audio: AudioCardConfig | None = None
    """Optional speech-serving configuration (TTS/STT kind, audio formats,
    streaming/realtime support, voices, reference audio, translation, sample
    rates); ``None`` for non-speech models."""
    tooling: ToolingCardConfig | None = None
    """Optional tool-calling configuration (support, call format, builtin tools);
    ``None`` falls back to family defaults."""
    runtime: RuntimeCapabilityCardConfig | None = None
    """Optional runtime-behavior configuration (prompt renderer, output parser,
    MTP/speculative-decoding sidecar, MLX knobs); ``None`` falls back to defaults."""
    placement: PlacementCardConfig = PlacementCardConfig()
    """Where the model is allowed to run and which backend is preferred: the
    ``compatible_backends`` hard filter and ``backend_preference`` soft score the
    planner uses to route the model to suitable nodes."""

    @model_validator(mode="after")
    def _fill_vision_weights_repo(self) -> "ModelCard":
        if self.vision is not None and not self.vision.weights_repo:
            object.__setattr__(
                self,
                "vision",
                self.vision.model_copy(
                    update={"weights_repo": str(self.artifact_repository)}
                ),
            )
        return self

    @model_validator(mode="after")
    def _require_projector_artifact_pin(self) -> "ModelCard":
        """Bind a served projector to an exact GGUF and immutable revision."""

        if self.vision is None or not self.vision.has_pinned_projector:
            return self
        if self.gguf_file is None:
            raise ValueError("a pinned vision projector requires gguf_file")
        if self.source_revision is None:
            raise ValueError("a pinned vision projector requires source_revision")
        return self

    @model_validator(mode="after")
    def _require_bundle_revision_and_selected_file(self) -> "ModelCard":
        """Bind a bundle manifest to one immutable upstream repository state."""

        bundle = self.artifact_bundle
        if bundle is None:
            return self
        if self.source_revision is None:
            raise ValueError("an artifact bundle requires source_revision")
        paths = {item.path for item in bundle.files}
        if self.gguf_file is not None and self.gguf_file not in paths:
            raise ValueError("artifact bundle must contain the selected GGUF")
        return self

    registry_card_id: Annotated[str, Field(pattern=r"^card_[a-z2-7]{52}$")] | None = (
        None
    )
    """Immutable content-derived registry card id, or ``None`` for local cards."""
    registry_snapshot_id: str | None = None
    """Signed registry snapshot that supplied this runtime card."""
    registry_provenance: Literal["foxlight", "agent", "community"] | None = None
    """Audited registry origin, kept separate from immutable artifact identity."""
    registry_architecture: str | None = None
    """Trusted upstream architecture identity used for support-matrix joins."""
    registry_artifact_format: str | None = None
    """Exact signed artifact format used for support-matrix joins."""
    registry_capability_claims: tuple[RegistryCapabilityClaim, ...] = ()
    """Open signed model/artifact capability claims, independent of engines."""

    @field_validator("registry_capability_claims", mode="before")
    @classmethod
    def _coerce_registry_capability_claims(cls, value: object) -> object:
        """Coerce TOML arrays-of-tables into the immutable runtime tuple."""
        if isinstance(value, list):
            return tuple(cast("list[object]", value))
        return value

    @model_validator(mode="after")
    def _require_registry_companion_revisions(self) -> "ModelCard":
        """Reject signed cards whose separate companion sources are mutable."""
        if self.registry_card_id is None:
            return self
        self.require_immutable_external_companions(context="signed registry cards")
        return self

    def require_immutable_external_companions(self, *, context: str) -> None:
        """Reject external companion repositories without immutable revisions.

        Args:
            context: Human-readable trust boundary included in validation errors.

        Raises:
            ValueError: If an external companion repository can resolve mutable
                bytes because its matching revision is absent.
        """
        base_repository = str(self.artifact_repository)
        companions: list[tuple[str, str | None, str | None]] = []
        if self.vision is not None:
            companions.extend(
                (
                    (
                        "vision.weights_repo",
                        self.vision.weights_repo,
                        self.vision.weights_revision,
                    ),
                    (
                        "vision.processor_repo",
                        self.vision.processor_repo,
                        self.vision.processor_revision,
                    ),
                )
            )
        if self.runtime is not None:
            companions.extend(
                (
                    (
                        "runtime.mtp_sidecar_repo",
                        self.runtime.mtp_sidecar_repo,
                        self.runtime.mtp_sidecar_revision,
                    ),
                    (
                        "runtime.assistant_model_repo",
                        self.runtime.assistant_model_repo,
                        self.runtime.assistant_model_revision,
                    ),
                    (
                        "runtime.served_spec_draft_repo",
                        self.runtime.served_spec_draft_repo,
                        self.runtime.served_spec_draft_revision,
                    ),
                    (
                        "runtime.vllm_spec_draft_repo",
                        self.runtime.vllm_spec_draft_repo,
                        self.runtime.vllm_spec_draft_revision,
                    ),
                )
            )
        for field_name, repository, revision in companions:
            if repository and repository != base_repository and revision is None:
                revision_field = f"{field_name.removesuffix('_repo')}_revision"
                raise ValueError(
                    f"{context} with {field_name} require immutable "
                    f"{revision_field}"
                )

    @property
    def artifact_repository(self) -> ModelId:
        """Return the upstream repository independently of the artifact alias."""
        return self.source_repository or self.model_id

    @model_validator(mode="after")
    def _validate_pipeline_split_limit(self) -> "ModelCard":
        """Require a constrained split boundary to lie inside the model."""
        split_limit = self.placement.max_pipeline_split_layer
        if split_limit is not None and split_limit >= self.n_layers:
            raise ValueError(
                "placement.max_pipeline_split_layer must be smaller than n_layers"
            )
        return self

    @field_validator("tasks", mode="before")
    @classmethod
    def _validate_tasks(cls, v: list[str | ModelTask]) -> list[ModelTask]:
        return [item if isinstance(item, ModelTask) else ModelTask(item) for item in v]

    async def save(self, path: Path) -> None:
        async with await open_file(path, "w") as f:
            excluded_fields = {"is_custom"}
            if not self.qualification_only:
                excluded_fields.add("qualification_only")
            py = self.model_dump(exclude_none=True, exclude=excluded_fields)
            data = tomlkit.dumps(py)  # pyright: ignore[reportUnknownMemberType]
            await f.write(data)

    async def save_to_custom_dir(self) -> None:
        await aios.makedirs(str(_custom_cards_dir), exist_ok=True)
        await self.save(_custom_cards_dir / (self.model_id.normalize() + ".toml"))

    @staticmethod
    async def load_from_path(path: Path) -> "ModelCard":
        async with await open_file(path, "r") as f:
            py = tomlkit.loads(await f.read())
            return ModelCard.model_validate(py)

    @staticmethod
    async def load(model_id: ModelId) -> "ModelCard":
        """Load an already-authorized card without discovering new Hub content.

        Args:
            model_id: Exact selectable model alias already present in the signed,
                bundled, installed, or operator-added catalog.

        Returns:
            The effective catalog card for ``model_id``.

        Raises:
            ValueError: If the alias has not entered the catalog through an
                authorization boundary.

        Side effects:
            May refresh signed registry metadata. It never fetches model metadata
            from Hugging Face or persists an unknown custom card.
        """
        await _refresh_card_cache_if_due()
        if (mc := _card_cache.get(model_id)) is not None:
            return mc

        raise ValueError(
            f"Unknown model {model_id}; add it through POST /models/add before use"
        )

    @staticmethod
    async def load_or_fetch_from_hf(model_id: ModelId) -> "ModelCard":
        """Load a known card or explicitly discover and persist one from the Hub.

        This helper is reserved for trusted local tooling. Network APIs must use
        :meth:`load` so a read or launch request cannot silently become a model
        authorization mutation.

        Args:
            model_id: Exact catalog alias or Hugging Face repository identifier.

        Returns:
            The existing card, or a newly generated immutable custom card.

        Side effects:
            For an unknown repository, reads bounded Hugging Face metadata and
            persists the generated card in the custom-card directory.
        """
        await _refresh_card_cache_if_due()
        if (mc := _card_cache.get(model_id)) is not None:
            return mc

        mc = await ModelCard.fetch_from_hf(model_id)
        await mc.save_to_custom_dir()
        _card_cache[model_id] = mc
        return mc

    @staticmethod
    async def fetch_from_hf(
        model_id: ModelId,
        gguf_file: str | None = None,
        source_revision: str | None = None,
    ) -> "ModelCard":
        """Build a model card from Hugging Face metadata.

        This is a pure fetch — it does NOT save to disk or update the cache.
        Persistence is handled by the event-sourcing layer (worker event handler).

        Detects GGUF repos (which `mlx-lm` cannot load) and builds a llama.cpp
        card for them instead of the default MLX/safetensors card. When
        ``gguf_file`` is supplied, the resulting card pins that exact repository
        file instead of applying the default quant preference.

        Args:
            model_id: Hugging Face repository identifier.
            gguf_file: Optional exact repo-relative GGUF path to pin.
            source_revision: Optional immutable Hugging Face commit to inspect
                and persist on the resulting card. When omitted, resolve
                ``main`` once and pin the returned commit before inspecting any
                artifact metadata.

        Returns:
            A custom model card derived from repository metadata.

        Raises:
            ValueError: The requested GGUF path is not a weight file in the repo,
                or a GGUF path is supplied for a non-GGUF repository.
        """
        source_revision = await _resolve_hf_source_revision(
            model_id,
            source_revision,
        )

        # GGUF detection remains a best-effort probe after immutable revision
        # resolution. A repository whose manifest cannot prove GGUF falls
        # through to the safetensors metadata path for that same commit.
        try:
            gguf_files = gguf_weight_siblings(model_id, source_revision)
        except Exception as exc:  # noqa: BLE001  (best-effort probe, see above)
            logger.debug(f"GGUF probe for {model_id} failed ({exc}); assuming non-GGUF")
            gguf_files = []
        if gguf_files:
            return await ModelCard._fetch_gguf_from_hf(
                model_id,
                gguf_files,
                gguf_file=gguf_file,
                source_revision=source_revision,
            )
        if gguf_file is not None:
            raise ValueError(
                f"Requested GGUF file {gguf_file!r}, but {model_id} has no GGUF weights"
            )

        # TODO: failure if files do not exist
        config_data = await fetch_config_data(model_id, source_revision)
        num_layers = config_data.layer_count
        mem_size_bytes = await fetch_safetensors_size(model_id, source_revision)

        return ModelCard(
            model_id=ModelId(model_id),
            storage_size=mem_size_bytes,
            n_layers=num_layers,
            hidden_size=config_data.hidden_size or 0,
            supports_tensor=config_data.supports_tensor,
            num_key_value_heads=config_data.num_key_value_heads,
            context_length=config_data.max_position_embeddings or 0,
            tasks=[ModelTask.TextGeneration],
            source_revision=source_revision,
            trust_remote_code=True,
            is_custom=True,
            generator_revision=CARD_GENERATOR_REVISION,
            vision=config_data.vision,
        )

    @staticmethod
    async def _fetch_gguf_from_hf(
        model_id: ModelId,
        gguf_files: "list[tuple[str, int]]",
        *,
        gguf_file: str | None = None,
        source_revision: str | None = None,
    ) -> "ModelCard":
        """Build a llama.cpp model card for a GGUF repo.

        Sizes the weights from the GGUF file the runner would actually load
        (`select_gguf_file` picks the first sorted file + its shard group).
        Structural fields come from `config.json` when the repo ships one (most
        community GGUF repos do); a bare repo with no usable config.json has its
        metadata read straight from the selected GGUF file's binary header via a
        ranged read of the file start (#327), so neither path fabricates the
        layer/hidden sizes placement's memory and KV-budget math depend on.
        Stamps the llama.cpp backend tags so placement routes the model only to
        nodes with a llama.cpp engine and prefers a GPU backend.
        """
        selected = (
            select_requested_gguf(gguf_file, gguf_files)
            if gguf_file is not None
            else select_preferred_gguf(gguf_files)
        )
        selected_size = gguf_shard_group_size(selected, gguf_files)

        # Structural metadata comes from config.json, which most community GGUF
        # repos (bartowski, unsloth, mlx-community) ship alongside the weights.
        # Treat a missing config.json (FileNotFoundError) OR a present-but-unusable
        # one (ValidationError, e.g. no num_hidden_layers, which ConfigData
        # requires) as "no usable config" and fall back to the GGUF header. HF
        # auth / rate-limit / transient network errors are neither and propagate
        # unchanged instead of being mislabeled as "no config.json".
        try:
            config_data = (
                await fetch_config_data(model_id, source_revision)
                if source_revision is not None
                else await fetch_config_data(model_id)
            )
        except (FileNotFoundError, ValidationError):
            config_data = None

        if (
            config_data is not None
            and config_data.layer_count
            and (config_data.hidden_size)
        ):
            n_layers = config_data.layer_count
            hidden_size = config_data.hidden_size
            num_key_value_heads = config_data.num_key_value_heads
            context_length = config_data.max_position_embeddings or 0
        else:
            # No usable config.json: read the structural fields from the GGUF
            # binary header. ``selected`` is the first shard, which carries the
            # metadata block, so a ranged read of its start is enough.
            reason = "absent" if config_data is None else "missing layer/hidden sizes"
            logger.info(
                f"GGUF repo {model_id} config.json {reason}; reading model "
                f"metadata from the GGUF header of {selected}"
            )
            from skulk.download.download_utils import range_read

            async def _fetch(offset: int, length: int) -> bytes:
                return await range_read(
                    model_id,
                    source_revision or "main",
                    selected,
                    offset,
                    length,
                )

            fields = await read_gguf_structural_fields(_fetch)
            n_layers = fields.n_layers
            hidden_size = fields.hidden_size
            num_key_value_heads = fields.num_key_value_heads
            context_length = fields.context_length

        # Mark the card vision-capable so the llama.cpp runner loads the mmproj
        # projector (#128, #346). Prefer the rich config.json vision_config when
        # the repo ships one (image_token_id, model_type). Otherwise, many popular
        # GGUF VLM repos (e.g. bartowski) ship NO config.json at all, so fall back
        # to the projector's presence as the vision signal and stamp a minimal
        # vision config: the llama.cpp chat handler inserts image features itself
        # and never needs image_token_id, and an empty model_type routes it to the
        # general multimodal handler. The mmproj weights are fetched via the
        # projector glob in gguf_allow_patterns, not from config.json.
        vision = (
            getattr(config_data, "vision", None) if config_data is not None else None
        )
        if vision is None and gguf_repo_has_projector(model_id, source_revision):
            logger.info(
                f"GGUF repo {model_id} ships an mmproj projector but no vision "
                "config; marking vision-capable with the general handler"
            )
            vision = VisionCardConfig()

        return ModelCard(
            model_id=ModelId(model_id),
            storage_size=selected_size,
            n_layers=n_layers,
            hidden_size=hidden_size,
            # llama.cpp runs single-node in Skulk (no tensor parallelism).
            supports_tensor=False,
            num_key_value_heads=num_key_value_heads,
            context_length=context_length,
            tasks=[ModelTask.TextGeneration],
            quantization=_gguf_quant_label(selected),
            gguf_file=selected,
            source_revision=source_revision,
            vision=vision,
            trust_remote_code=False,
            is_custom=True,
            generator_revision=CARD_GENERATOR_REVISION,
            placement=PlacementCardConfig(
                # Both llama.cpp engines, mirroring the bundled GGUF text
                # cards (#607): the served llama_server tags rank first so a
                # node running llama-server gets its concurrency slots, and
                # only the served engine can pool multiple nodes via RPC
                # (a llama_cpp-only card is silently ineligible for every
                # multi-node GGUF placement). Nodes without a served binary
                # fall through to in-process llama_cpp unchanged.
                compatible_backends=frozenset(
                    {
                        "llama_server-vulkan",
                        "llama_server-rocm",
                        "llama_server-cuda",
                        "llama_server-cpu",
                        "llama_cpp-vulkan",
                        "llama_cpp-rocm",
                        "llama_cpp-cuda",
                        "llama_cpp-cpu",
                    }
                ),
                # Served engine first, then a GPU backend over CPU; the GPU
                # ordering is a sensible default a card author can tune per
                # model (Vulkan vs ROCm performance is model-dependent).
                backend_preference=(
                    "llama_server-vulkan",
                    "llama_server-rocm",
                    "llama_server-cuda",
                    "llama_cpp-vulkan",
                    "llama_cpp-rocm",
                    "llama_cpp-cuda",
                    "llama_server-cpu",
                    "llama_cpp-cpu",
                ),
            ),
        )


def preserve_generated_card_constraints(
    generated: ModelCard,
    bundled: ModelCard | None,
) -> ModelCard:
    """Carry curated hard placement constraints into a generated override.

    Args:
        generated: Machine-generated Hugging Face metadata card.
        bundled: Existing curated card for the same model, when one exists.

    Returns:
        The generated card with any curated pipeline split boundary retained.

    Operator-authored cards have no generator stamp and remain authoritative.
    Generated cards are metadata caches, so they must not erase a bundled
    architecture invariant merely because the user added the same repository
    through the dashboard.
    """
    if (
        generated.generator_revision is None
        or bundled is None
        or bundled.is_custom
        or bundled.placement.max_pipeline_split_layer is None
    ):
        return generated
    placement = generated.placement.model_copy(
        update={"max_pipeline_split_layer": bundled.placement.max_pipeline_split_layer}
    )
    return generated.model_copy(update={"placement": placement})


def add_to_card_cache(card: "ModelCard") -> None:
    """Add or update a model card in the in-memory cache."""
    _card_cache[card.model_id] = card


def get_custom_card_storage_collision(model_id: ModelId) -> "ModelCard | None":
    """Return a distinct custom card that shares this alias's storage key.

    Args:
        model_id: Candidate alias whose normalized persistence key is being used.

    Returns:
        The conflicting custom card, or ``None`` when the key is unowned.
    """
    storage_key = model_id.normalize()
    return next(
        (
            card
            for card in _card_cache.values()
            if card.is_custom
            and card.model_id != model_id
            and card.model_id.normalize() == storage_key
        ),
        None,
    )


async def delete_custom_card(model_id: ModelId) -> bool:
    """Delete a user-added custom model card. Returns True if deleted.

    Rebuild the catalog through the same signed-registry selection used at
    startup. A direct bundled reload would temporarily resurrect revoked cards
    and restore the wrong source beneath a deleted registry override.
    """
    card_path = _custom_cards_dir / (ModelId(model_id).normalize() + ".toml")
    if await card_path.exists():
        stored_card = await ModelCard.load_from_path(card_path)
        if stored_card.model_id != model_id:
            raise ValueError(
                "custom model-card storage key belongs to a different alias"
            )
        await card_path.unlink()
        _card_cache.pop(model_id, None)
        await _refresh_card_cache()
        return True
    return False


class ConfigData(BaseModel):
    model_config = {"extra": "ignore"}  # Allow unknown fields

    architectures: list[str] | None = None
    hidden_size: Annotated[int, Field(ge=0)] | None = None
    num_key_value_heads: PositiveInt | None = None
    layer_count: int = Field(
        validation_alias=AliasChoices(
            "num_hidden_layers",
            "num_layers",
            "n_layer",
            "n_layers",
            "num_decoder_layers",
            "decoder_layers",
        )
    )
    max_position_embeddings: int | None = None
    vision: VisionCardConfig | None = None

    @property
    def supports_tensor(self) -> bool:
        return self.architectures in [
            ["Glm4MoeLiteForCausalLM"],
            ["GlmMoeDsaForCausalLM"],
            ["DeepseekV32ForCausalLM"],
            ["DeepseekV3ForCausalLM"],
            ["Qwen3NextForCausalLM"],
            ["Qwen3MoeForCausalLM"],
            ["Qwen3_5MoeForConditionalGeneration"],
            ["Qwen3_5ForConditionalGeneration"],
            ["MiniMaxM2ForCausalLM"],
            ["LlamaForCausalLM"],
            ["GptOssForCausalLM"],
            ["Step3p5ForCausalLM"],
            ["NemotronHForCausalLM"],
        ]

    @model_validator(mode="before")
    @classmethod
    def defer_to_text_config(cls, data: dict[str, Any], info: ValidationInfo):
        text_config = data.get("text_config")
        if text_config is not None:
            for field in [
                "architectures",
                "hidden_size",
                "num_key_value_heads",
                "num_hidden_layers",
                "num_layers",
                "n_layer",
                "n_layers",
                "num_decoder_layers",
                "decoder_layers",
                "max_position_embeddings",
            ]:
                if (val := text_config.get(field)) is not None:  # pyright: ignore[reportAny]
                    data[field] = val

        vision_config = data.get("vision_config")
        image_token_id = data.get("image_token_id")
        if vision_config is not None and image_token_id is not None:
            # Prefer top-level model_type (e.g. "gemma4") over
            # vision_config.model_type (e.g. "gemma4_vision") — the top-level
            # value matches the mlx_vlm.models.{model_type} import path.
            model_type = str(
                data.get("model_type", vision_config.get("model_type", ""))  # pyright: ignore[reportAny]
            )
            assert info.context is not None

            boi = data.get("boi_token_id")
            eoi = data.get("eoi_token_id")
            data["vision"] = VisionCardConfig(
                image_token_id=int(image_token_id),  # pyright: ignore[reportAny]
                model_type=model_type,
                weights_repo=info.context["model_id"],  # type: ignore
                boi_token_id=int(boi) if boi is not None else None,  # pyright: ignore[reportAny]
                eoi_token_id=int(eoi) if eoi is not None else None,  # pyright: ignore[reportAny]
            )

        return data


def _metadata_directory_name(model_id: ModelId, source_revision: str | None) -> str:
    """Return an isolated metadata cache directory name for one revision."""

    suffix = f"--revision-{source_revision}" if source_revision else ""
    return f"{model_id.normalize()}{suffix}"


async def fetch_config_data(
    model_id: ModelId, source_revision: str | None = None
) -> ConfigData:
    """Download and parse ``config.json`` at an optional immutable revision."""
    from skulk.download.download_utils import (
        download_file_with_retry,
        ensure_models_dir,
    )

    target_dir = (await ensure_models_dir()) / _metadata_directory_name(
        model_id, source_revision
    )
    await aios.makedirs(target_dir, exist_ok=True)
    config_path = await download_file_with_retry(
        model_id,
        source_revision or "main",
        "config.json",
        target_dir,
        lambda curr_bytes, total_bytes, is_renamed: logger.debug(
            f"Downloading config.json for {model_id}: {curr_bytes}/{total_bytes} ({is_renamed=})"
        ),
    )
    async with aiofiles.open(config_path, "r") as f:
        return ConfigData.model_validate_json(
            await f.read(), context={"model_id": str(model_id)}
        )


async def fetch_safetensors_size(
    model_id: ModelId, source_revision: str | None = None
) -> Memory:
    """Get model size at an optional immutable revision."""
    from skulk.download.download_utils import (
        download_file_with_retry,
        ensure_models_dir,
    )
    from skulk.shared.types.worker.downloads import ModelSafetensorsIndex

    target_dir = (await ensure_models_dir()) / _metadata_directory_name(
        model_id, source_revision
    )
    await aios.makedirs(target_dir, exist_ok=True)
    index_path = await download_file_with_retry(
        model_id,
        source_revision or "main",
        "model.safetensors.index.json",
        target_dir,
        lambda curr_bytes, total_bytes, is_renamed: logger.debug(
            f"Downloading model.safetensors.index.json for {model_id}: {curr_bytes}/{total_bytes} ({is_renamed=})"
        ),
    )
    async with aiofiles.open(index_path, "r") as f:
        index_data = ModelSafetensorsIndex.model_validate_json(await f.read())

    metadata = index_data.metadata
    if metadata is not None:
        return Memory.from_bytes(metadata.total_size)

    info = (
        model_info(model_id, revision=source_revision)
        if source_revision is not None
        else model_info(model_id)
    )
    if info.safetensors is None:
        raise ValueError(f"No safetensors info found for {model_id}")
    return Memory.from_bytes(info.safetensors.total)


def gguf_repo_has_projector(
    model_id: ModelId, source_revision: str | None = None
) -> bool:
    """Whether a GGUF repo ships a multimodal projector (``*mmproj*.gguf``).

    A vision GGUF (LLaVA/Qwen-VL style) carries its projector as a separate
    ``mmproj`` file. Many popular GGUF VLM repos ship no ``config.json`` (so the
    config-based vision detection cannot fire), but the projector's presence is
    itself a reliable "this is a vision model" signal. Best-effort: returns
    ``False`` if the HF probe fails, so a transient error never misclassifies.
    """
    try:
        info = (
            model_info(model_id, revision=source_revision, files_metadata=True)
            if source_revision is not None
            else model_info(model_id, files_metadata=True)
        )
    except Exception:  # noqa: BLE001 - best-effort probe, mirror gguf_weight_siblings
        return False
    siblings = info.siblings or []
    return any(
        sibling.rfilename.endswith(".gguf") and "mmproj" in sibling.rfilename.lower()
        for sibling in siblings
    )


def gguf_weight_siblings(
    model_id: ModelId, source_revision: str | None = None
) -> "list[tuple[str, int]]":
    """List a repo's GGUF weight files (filename, size) via the HF API.

    Excludes multimodal projector files (``mmproj*``), which are not the LM
    weights. Returns an empty list for a non-GGUF repo, so callers use this as a
    "is this a GGUF model?" probe. Sizes are bytes (0 when HF omits the size).
    """
    info = (
        model_info(model_id, revision=source_revision, files_metadata=True)
        if source_revision is not None
        else model_info(model_id, files_metadata=True)
    )
    siblings = info.siblings or []
    return [
        (sibling.rfilename, sibling.size or 0)
        for sibling in siblings
        if sibling.rfilename.endswith(".gguf")
        and "mmproj" not in sibling.rfilename.lower()
    ]


# Preferred GGUF quantizations, best first. Q4_K_M is the de-facto default
# (good quality/size); unquantized (BF16/F16/F32) is deprioritized hard so a
# multi-quant repo never defaults to the full-precision weights (#334).
_GGUF_QUANT_PREFERENCE: Final[tuple[str, ...]] = (
    "q4_k_m",
    "q4_k_s",
    "q5_k_m",
    "q5_k_s",
    "q6_k",
    "q4_0",
    "q5_0",
    "q8_0",
    "q3_k_m",
    "q3_k_l",
    "q3_k_s",
    "q2_k",
    "iq4_xs",
    "iq4_nl",
    "iq4",
    "iq3",
    "iq2",
    "iq1",
)
_GGUF_UNQUANTIZED: Final[tuple[str, ...]] = ("bf16", "f16", "fp16", "f32", "fp32")
_GGUF_RANK_UNRECOGNIZED: Final = 1_000  # unknown quant: after known quants
_GGUF_RANK_UNQUANTIZED: Final = 10_000  # full precision: dead last


def gguf_quant_rank(name: str) -> int:
    """Preference rank for a GGUF filename (lower is better); see #334."""
    low = name.rsplit("/", 1)[-1].lower()
    for index, marker in enumerate(_GGUF_QUANT_PREFERENCE):
        if marker in low:
            return index
    if any(token in low for token in _GGUF_UNQUANTIZED):
        return _GGUF_RANK_UNQUANTIZED
    return _GGUF_RANK_UNRECOGNIZED


def _gguf_quant_label(name: str) -> str:
    """Human quant label parsed from a GGUF filename (e.g. ``Q4_K_M``), or ``""``."""
    low = name.rsplit("/", 1)[-1].lower()
    for marker in _GGUF_QUANT_PREFERENCE:
        if marker in low:
            return marker.upper()
    for token in _GGUF_UNQUANTIZED:
        if token in low:
            return token.upper()
    return ""


# Companion artifacts a GGUF repo ships ALONGSIDE the model: speculative
# drafters (dspark/dflash/draft), importance-matrix calibration files, and
# multimodal projectors. Useless (or worse, actively misleading) as the main
# model: a repo default that picked unsloth's ``dspark-*-Q8_0.gguf`` drafter
# would stage a 10 GB draft model wearing a 284B model's name. Word-boundary
# matched so ordinary model names containing these letters don't trip it.
_COMPANION_GGUF_PATTERN: Final = re.compile(
    r"(?:^|[^a-z0-9])(?:mmproj|imatrix|dspark|dflash|draft)(?:$|[^a-z])"
)


def is_companion_gguf(name: str) -> bool:
    """True when a GGUF filename names a companion artifact, not LM weights.

    Companions are speculative-decoding drafters (``dspark``/``dflash``/
    ``draft``), importance-matrix calibration files, and multimodal
    projectors. They are ranked dead-last by default selection so a repo
    default never picks one, while a drafter-only repo (a published draft
    companion) still resolves.
    """
    return _COMPANION_GGUF_PATTERN.search(name.rsplit("/", 1)[-1].lower()) is not None


def select_preferred_gguf(gguf_files: "list[tuple[str, int]]") -> str:
    """Pick the GGUF weights file to load: best quant, then basename order.

    Prefers a real quantization (Q4_K_M first) over the unquantized BF16/F16 a
    multi-quant repo also ships (#334), and ranks companion artifacts
    (drafters, imatrix files) behind every real quant so a repo default never
    stages a speculator as the model. The basename tie-break makes the choice
    deterministic and, for a shard group, picks the first shard. The runner's
    ``select_gguf_file`` falls back to this same ranking when the card does not
    pin a file, so download, sizing, and loading all agree.
    """
    return min(
        (name for name, _ in gguf_files),
        key=lambda name: (
            is_companion_gguf(name),
            gguf_quant_rank(name),
            name.rsplit("/", 1)[-1],
        ),
    )


def select_requested_gguf(
    requested: str,
    gguf_files: "list[tuple[str, int]]",
) -> str:
    """Validate a requested GGUF path and return its loadable entrypoint.

    Args:
        requested: Repo-relative GGUF path supplied by the caller.
        gguf_files: Weight-file inventory returned by :func:`gguf_weight_siblings`.

    Returns:
        The requested path for a single-file quant, or the first file in the
        requested shard group for split weights.

    Raises:
        ValueError: The requested path is not one of the repository's GGUF weights.
    """
    available = {name for name, _ in gguf_files}
    if requested not in available:
        raise ValueError(f"Requested GGUF file {requested!r} was not found in the repo")
    requested_group = _gguf_shard_base(requested)
    if requested_group is None:
        return requested

    # Backends open the first shard and discover the remaining files from it.
    # Preserve the selected quant group while normalizing a pasted later shard
    # to the same entrypoint used by automatic GGUF selection.
    return min(name for name in available if _gguf_shard_base(name) == requested_group)


# Glob for the multimodal projector a vision GGUF repo ships alongside the LM
# weights (LLaVA-style: ``mmproj-<...>.gguf``). It never matches the selected LM
# quant's shard group, so it must be allow-listed explicitly or llama.cpp cannot
# do image inference (#346). ``*mmproj*`` (not ``mmproj*``) so it also matches a
# projector nested in a subdirectory, since HuggingFace allow-patterns match the
# whole repo-relative path. A text-only repo has none, so this matches nothing
# and costs nothing; a repo shipping several projector quants downloads each
# (small relative to the weights, and llama.cpp loads one).
_GGUF_PROJECTOR_PATTERN: Final = "*mmproj*.gguf"


def gguf_allow_patterns(
    gguf_file: str,
    projector_file: str | None = None,
) -> list[str]:
    """Download allow-patterns for a card's selected GGUF (its shard group +
    any multimodal projector).

    A single-file quant downloads just itself; a sharded quant downloads its
    whole ``<base>-NNNNN-of-NNNNN`` group via a glob. This is what lets the
    downloader fetch only the chosen quant instead of every quant a multi-quant
    repo hosts (#332). The ``mmproj`` projector glob is always included so a
    vision GGUF model fetches its projector too (#346); it matches nothing on a
    text-only repo. Caller adds non-weight files (e.g. ``config.json``).
    """
    projector_pattern = projector_file or _GGUF_PROJECTOR_PATTERN
    base = _gguf_shard_base(gguf_file)
    if base is None:
        return [gguf_file, projector_pattern]
    return [f"{base}-*-of-*.gguf", projector_pattern]


def gguf_shard_group_size(selected: str, gguf_files: "list[tuple[str, int]]") -> Memory:
    """Total bytes of ``selected`` plus its sibling shards (its shard group).

    A single-file quant sums to itself; a sharded quant sums every file sharing
    its ``<base>-NNNNN-of-NNNNN`` group. Keeps ``storage_size`` consistent with
    what actually loads, not the sum of every quant the repo hosts.
    """
    base = _gguf_shard_base(selected)
    if base is None:
        return Memory.from_bytes(dict(gguf_files)[selected])
    return Memory.from_bytes(
        sum(size for name, size in gguf_files if _gguf_shard_base(name) == base)
    )


def _gguf_shard_base(name: str) -> str | None:
    """Return the shard-group base of a GGUF filename, or ``None`` if unsharded.

    ``foo-00001-of-00003.gguf`` -> ``foo``; ``foo.gguf`` -> ``None``. Detects the
    ``-NNNNN-of-NNNNN.gguf`` suffix without a regex (re is not imported here).
    The base itself may contain dashes (e.g. ``Qwen2.5-7B-Instruct-Q4_K_M``), so
    we split only the trailing three ``-`` tokens.
    """
    stem = name[: -len(".gguf")] if name.endswith(".gguf") else name
    parts = stem.rsplit("-", 3)
    if (
        len(parts) == 4
        and parts[1].isdigit()
        and parts[2] == "of"
        and parts[3].isdigit()
    ):
        return parts[0]
    return None


# --- GGUF binary header parsing (#327) -------------------------------------
#
# A GGUF file begins with a metadata block (magic, version, tensor count, then
# a list of typed key/value pairs) followed by the tensor data. The structural
# fields a model card needs (layer count, hidden size, KV-head count, context
# length) live in that block under arch-prefixed keys, so they can be read from
# the start of the file via a ranged HTTP read instead of pulling the multi-GB
# weights. This is the fallback for GGUF repos that ship no ``config.json``.
#
# Spec: https://github.com/ggml-org/ggml/blob/master/docs/gguf.md

_GGUF_MAGIC: Final = b"GGUF"
# Lengths/counts are 64-bit in GGUF v2/v3; v1 used 32-bit and is obsolete.
_GGUF_SUPPORTED_VERSIONS: Final = frozenset({2, 3})

# GGUF metadata value type tags.
_GGUF_TYPE_STRING: Final = 8
_GGUF_TYPE_ARRAY: Final = 9
# Scalar value type tag -> struct format. ``bool`` (tag 7) is read as a byte;
# we deliberately do not store it as an int field (see the parse loop).
_GGUF_SCALAR_FMT: Final[dict[int, str]] = {
    0: "<B",  # uint8
    1: "<b",  # int8
    2: "<H",  # uint16
    3: "<h",  # int16
    4: "<I",  # uint32
    5: "<i",  # int32
    6: "<f",  # float32
    7: "<B",  # bool (stored as one byte)
    10: "<Q",  # uint64
    11: "<q",  # int64
    12: "<d",  # float64
}
_GGUF_SCALAR_SIZE: Final[dict[int, int]] = {
    tag: struct.calcsize(fmt) for tag, fmt in _GGUF_SCALAR_FMT.items()
}

# Structural keys we read, relative to ``general.architecture`` (e.g. for arch
# ``llama`` we read ``llama.block_count``). These mirror config.json's
# layer_count / hidden_size / num_key_value_heads / max_position_embeddings.
_GGUF_KEY_BLOCK_COUNT: Final = "block_count"
_GGUF_KEY_EMBEDDING_LENGTH: Final = "embedding_length"
_GGUF_KEY_HEAD_COUNT_KV: Final = "attention.head_count_kv"
_GGUF_KEY_CONTEXT_LENGTH: Final = "context_length"
_GGUF_WANTED_SUFFIXES: Final = (
    _GGUF_KEY_BLOCK_COUNT,
    _GGUF_KEY_EMBEDDING_LENGTH,
    _GGUF_KEY_HEAD_COUNT_KV,
    _GGUF_KEY_CONTEXT_LENGTH,
)
# The keys a card cannot be built without; head_count_kv and context_length are
# best-effort (default to None / 0). Used to decide the early stop at the start
# of the tokenizer section when a best-effort key is simply absent.
_GGUF_REQUIRED_SUFFIXES: Final = (
    _GGUF_KEY_BLOCK_COUNT,
    _GGUF_KEY_EMBEDDING_LENGTH,
)


class GgufStructuralFields(NamedTuple):
    """Structural model dimensions read from a GGUF metadata header (#327)."""

    n_layers: int
    hidden_size: int
    num_key_value_heads: int | None
    context_length: int


class _GgufHeaderReader:
    """Sequential cursor over a GGUF metadata header fetched on demand.

    Bytes are pulled through an injected ``fetch(offset, length)`` coroutine
    (HTTP range in production, an in-memory blob in tests) into a growing buffer
    and cached, so the header is read in a few windows rather than one giant
    request. The cursor advances as typed values are read; large arrays (e.g. a
    tokenizer vocabulary) are skipped by advancing the cursor, fetching more
    only if a wanted key happens to sit past them.
    """

    _WINDOW: Final = 1 << 20  # 1 MiB per fetch; structural keys sit well inside.

    def __init__(self, fetch: "Callable[[int, int], Awaitable[bytes]]") -> None:
        self._fetch = fetch
        self._buf = bytearray()
        self._eof = False
        self.pos = 0

    async def _ensure(self, end: int) -> None:
        """Fetch until the buffer holds at least ``end`` bytes (or EOF)."""
        while len(self._buf) < end and not self._eof:
            start = len(self._buf)
            # Cap each fetch at one window and loop, so a large forward jump (a
            # bulk array skip past ``end``) never balloons into a single huge
            # range request; the loop keeps memory/request size window-bounded.
            chunk = await self._fetch(start, self._WINDOW)
            # Only an empty read is EOF; a short read is a partial transport
            # chunk, so keep fetching from the new offset rather than stopping.
            if not chunk:
                self._eof = True
                return
            self._buf.extend(chunk)

    async def _take(self, n: int) -> bytes:
        await self._ensure(self.pos + n)
        if self.pos + n > len(self._buf):
            raise ValueError("GGUF header truncated before the wanted metadata")
        data = bytes(self._buf[self.pos : self.pos + n])
        self.pos += n
        return data

    async def _u32(self) -> int:
        return cast(int, struct.unpack("<I", await self._take(4))[0])

    async def _u64(self) -> int:
        return cast(int, struct.unpack("<Q", await self._take(8))[0])

    async def read_string(self) -> str:
        length = await self._u64()
        return (await self._take(length)).decode("utf-8", errors="replace")

    async def read_value(self, value_type: int) -> "int | str | None":
        """Read one metadata value; return ints/strings, skip everything else.

        Returns the value for integer and string scalars (the only kinds the
        wanted keys use), and ``None`` for floats, bools, and arrays after
        advancing past them.
        """
        if value_type == _GGUF_TYPE_STRING:
            return await self.read_string()
        if value_type == _GGUF_TYPE_ARRAY:
            await self._skip_array()
            return None
        fmt = _GGUF_SCALAR_FMT.get(value_type)
        if fmt is None:
            raise ValueError(f"unknown GGUF metadata value type {value_type}")
        raw = await self._take(_GGUF_SCALAR_SIZE[value_type])
        # Floats and bools are not structural fields we read; only surface ints.
        if value_type in (6, 12, 7):  # float32, float64, bool
            return None
        return cast(int, struct.unpack(fmt, raw)[0])

    async def _skip_array(self) -> None:
        element_type = await self._u32()
        count = await self._u64()
        if element_type in _GGUF_SCALAR_SIZE:
            # Bulk-skip fixed-width elements (e.g. a token-score float array).
            self.pos += _GGUF_SCALAR_SIZE[element_type] * count
        elif element_type == _GGUF_TYPE_STRING:
            for _ in range(count):
                _ = await self.read_string()
        elif element_type == _GGUF_TYPE_ARRAY:
            for _ in range(count):
                await self._skip_array()
        else:
            raise ValueError(f"unknown GGUF array element type {element_type}")

    async def parse_structural_fields(self) -> GgufStructuralFields:
        """Read the structural model dimensions from this GGUF header.

        Reads ``general.architecture`` and the arch-prefixed ``block_count`` /
        ``embedding_length`` / ``attention.head_count_kv`` / ``context_length``
        keys. Stops as soon as all are seen, or, if a best-effort key is absent,
        at the start of the tokenizer section (the arch scalars always precede
        it), so a trailing multi-megabyte tokenizer array is never fetched.

        Raises:
            ValueError: The bytes are not a supported GGUF header, or the header
                lacks the architecture / layer / hidden-size keys needed to
                build a card.
        """
        if (await self._take(4)) != _GGUF_MAGIC:
            raise ValueError("not a GGUF file (bad magic)")
        version = await self._u32()
        if version not in _GGUF_SUPPORTED_VERSIONS:
            raise ValueError(f"unsupported GGUF version {version}")
        _ = await self._u64()  # tensor_count
        kv_count = await self._u64()

        architecture: str | None = None
        collected: dict[str, int] = {}

        def _has(suffixes: "tuple[str, ...]") -> bool:
            return architecture is not None and all(
                f"{architecture}.{suffix}" in collected for suffix in suffixes
            )

        for _ in range(kv_count):
            key = await self.read_string()
            # The arch-prefixed scalar keys precede the tokenizer section; once a
            # tokenizer key appears no more arch scalars follow, so if the
            # required fields are known, stop before reading a potentially huge
            # tokenizer array for best-effort fields that are simply absent.
            if key.startswith("tokenizer.") and _has(_GGUF_REQUIRED_SUFFIXES):
                break
            value = await self.read_value(await self._u32())
            if key == "general.architecture" and isinstance(value, str):
                architecture = value
            elif isinstance(value, int):
                collected[key] = value
            # Fast path: every wanted key (including best-effort ones) is in,
            # before any tokenizer array.
            if _has(_GGUF_WANTED_SUFFIXES):
                break

        if architecture is None:
            raise ValueError("GGUF header missing general.architecture")

        def field(suffix: str) -> int | None:
            return collected.get(f"{architecture}.{suffix}")

        n_layers = field(_GGUF_KEY_BLOCK_COUNT)
        hidden_size = field(_GGUF_KEY_EMBEDDING_LENGTH)
        if not n_layers or not hidden_size:
            raise ValueError(
                f"GGUF header for arch {architecture!r} is missing block_count / "
                "embedding_length"
            )
        return GgufStructuralFields(
            n_layers=n_layers,
            hidden_size=hidden_size,
            num_key_value_heads=field(_GGUF_KEY_HEAD_COUNT_KV) or None,
            context_length=field(_GGUF_KEY_CONTEXT_LENGTH) or 0,
        )


async def read_gguf_structural_fields(
    fetch: "Callable[[int, int], Awaitable[bytes]]",
) -> GgufStructuralFields:
    """Parse structural model dimensions from a GGUF metadata header.

    ``fetch(offset, length)`` supplies bytes from the start of the GGUF file
    (an HTTP range read in production, an in-memory blob in tests). See
    :meth:`_GgufHeaderReader.parse_structural_fields` for what is read.

    Raises:
        ValueError: The bytes are not a supported GGUF header, or the header
            lacks the architecture / layer / hidden-size keys needed to build a
            card.
    """
    return await _GgufHeaderReader(fetch).parse_structural_fields()
